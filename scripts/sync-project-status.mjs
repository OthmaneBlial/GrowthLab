#!/usr/bin/env node
// Local-only synchronization. No GitHub workflow, network call or auto-publish.
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const check = process.argv.slice(2).includes("--check");
if (process.argv.slice(2).some((arg) => arg !== "--check")) throw new Error("Usage: node scripts/sync-project-status.mjs [--check]");
const raw = await readFile(path.join(root, "docs/status.json"), "utf8");
const status = JSON.parse(raw);
if (status.schemaVersion !== 1 || !Number.isInteger(status.progressEstimate) || status.progressEstimate < 0 || status.progressEstimate > 100 || !/^\d{4}-\d{2}-\d{2}$/.test(status.updated)) throw new Error("Invalid project status version, estimate or date");
const plain = (value) => {
  if (typeof value !== "string" || !value.trim() || /[\r\n<>|]/.test(value)) throw new Error("Status text must be nonempty plain text on one line");
  return value.replaceAll("*", "\\*").replaceAll("[", "\\[").replaceAll("]", "\\]");
};
for (const key of ["delivered", "pending", "validation"]) if (!Array.isArray(status[key]) || !status[key].length) throw new Error(`Missing status list: ${key}`);
const xml = (value) => String(value).replaceAll("&", "&amp;").replaceAll("<", "&lt;").replaceAll('"', "&quot;");
const badge = (label, value) => {
  const left = Math.max(54, label.length * 7 + 18), right = value.length * 7 + 18;
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${left + right}" height="24" role="img" aria-label="${xml(`${label}: ${value}`)}"><title>${xml(`${label}: ${value}`)}</title><rect width="${left}" height="24" fill="#202725"/><rect x="${left}" width="${right}" height="24" fill="#17634f"/><g fill="#fff" font-family="Verdana,Arial,sans-serif" font-size="11" text-anchor="middle"><text x="${left / 2}" y="16">${xml(label)}</text><text x="${left + right / 2}" y="16">${xml(value)}</text></g></svg>\n`;
};
const progress = [
  "<!-- Generated by scripts/sync-project-status.mjs from docs/status.json. -->",
  `[![Project progress: about ${status.progressEstimate}% estimate](docs/assets/progress.svg)](docs/PROGRESS.md) [![Checks run locally; cloud CI disabled](docs/assets/checks.svg)](docs/PROGRESS.md)`,
  "",
  `**${plain(status.stage)} · about ${status.progressEstimate}% overall (subjective estimate) · updated ${status.updated}**`,
  "",
  `Current milestone: **${plain(status.milestone)}**.`,
  "",
  "**Working today**",
  "",
  ...status.delivered.map((item) => `- ${plain(item)}`),
  "",
  "| Validation | Current evidence |",
  "| --- | --- |",
  ...status.validation.map((item) => `| ${plain(item.name)} | **${plain(item.status)}** — ${plain(item.detail)} |`),
  "",
  "**Still ahead**",
  "",
  ...status.pending.map((item) => `- ${plain(item)}`),
].join("\n");
const links = [];
if (status.website?.published === true) {
  if (status.website.url !== "https://othmaneblial.github.io/GrowthLab/" || status.website.docsUrl !== "https://othmaneblial.github.io/GrowthLab/docs.html") throw new Error("Website identity does not match GrowthLab");
  links.push(`[Website](${status.website.url})`, `[Docs](${status.website.docsUrl})`);
} else links.push("[Documentation](docs/dashboard.md)");
if (status.release?.published === true) {
  if (!/^https:\/\/github\.com\/OthmaneBlial\/GrowthLab\/releases\/tag\/v[\w.-]+$/.test(status.release.url)) throw new Error("Release identity does not match GrowthLab");
  links.push(`[Alpha release](${status.release.url})`);
}
links.push("[Roadmap](docs/ROADMAP.md)", "[Contribute](CONTRIBUTING.md)");
let readme = await readFile(path.join(root, "README.md"), "utf8");
for (const [name, content] of [["project-links", links.join(" · ")], ["project-status", progress]]) {
  const pattern = new RegExp(`<!-- ${name}:start -->[\\s\\S]*?<!-- ${name}:end -->`, "g");
  if ([...readme.matchAll(pattern)].length !== 1) throw new Error(`Expected one README ${name} block`);
  readme = readme.replace(pattern, `<!-- ${name}:start -->\n${content}\n<!-- ${name}:end -->`);
}
const outputs = new Map([
  ["README.md", readme],
  ["docs/assets/progress.svg", badge("project estimate", `about ${status.progressEstimate}%`)],
  ["docs/assets/checks.svg", badge("checks", "local only")],
  ["site/status.json", raw],
]);
for (const [source, target] of [["docs/PROGRESS.md", "PROGRESS.md"], ["docs/ROADMAP.md", "ROADMAP.md"], ["CHANGELOG.md", "CHANGELOG.md"]]) outputs.set(`site/content/${target}`, await readFile(path.join(root, source), "utf8"));
let stale = 0;
for (const [relative, content] of outputs) {
  const target = path.join(root, relative);
  let current;
  try { current = await readFile(target, "utf8"); } catch (error) { if (error.code !== "ENOENT") throw error; }
  if (current === content) continue;
  if (check) { process.stderr.write(`Out of sync: ${relative}\n`); stale++; }
  else { await mkdir(path.dirname(target), { recursive: true }); await writeFile(target, content); }
}
if (stale) process.exitCode = 1;
else process.stdout.write(check ? "README and website status are synchronized.\n" : "Synchronized README and website status from docs/status.json.\n");
